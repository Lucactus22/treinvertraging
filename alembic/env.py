"""Alembic environment: models' Base metadata, DATA_DIR-based URL (unless one is configured)."""

from __future__ import annotations

from logging.config import fileConfig

from alembic import context

from treinvertraging.config import get_settings
from treinvertraging.db import make_engine
from treinvertraging.models import Base

config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name, disable_existing_loggers=False)

target_metadata = Base.metadata


def _url() -> str:
    url = config.get_main_option("sqlalchemy.url")
    if url:
        return url.replace("%%", "%")
    settings = get_settings()
    settings.DATA_DIR.mkdir(parents=True, exist_ok=True)
    return settings.db_url


def run_migrations_offline() -> None:
    context.configure(
        url=_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        render_as_batch=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    engine = make_engine(_url())
    with engine.connect() as connection:
        context.configure(connection=connection, target_metadata=target_metadata, render_as_batch=True)
        with context.begin_transaction():
            context.run_migrations()
    engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
